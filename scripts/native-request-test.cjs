assert.deepEqual(JSON.parse(nativeTurnMeta(run)['x-codex-turn-metadata']),{session_id:run.threadId,thread_id:run.threadId,turn_id:run.turnId,thread_source:'user'});
for(const invalid of [null,{}, {...run,cancelled:true},{...run,turnId:null}])assert.throws(()=>nativeTurnMeta(invalid),/有效/);
