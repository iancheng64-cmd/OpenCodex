assert.equal(routed.params.threadId,run.threadId);
assert.equal(routed.params.turnId,run.turnId);
assert.equal(routed.id,73);
assert.deepEqual(routed.params._meta,original.params._meta);
assert.equal(JSON.stringify(original),frozen);
assert.equal(routeNativeRequest(original,'other-local',run),null);
assert.equal(routeNativeRequest(original,'local-ephemeral',{...run,cancelled:true}),null);
