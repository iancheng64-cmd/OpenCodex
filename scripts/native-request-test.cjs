'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const {routeNativeRequest,nativeTurnMeta}=require('../src/native-request.cjs');
const original={id:73,method:'mcpServer/elicitation/request',params:{threadId:'local-ephemeral',turnId:null,serverName:'cua_repl',mode:'form',_meta:{codex_approval_kind:'mcp_tool_call',connector_id:'computer-use',persist:['session','always']},message:'Allow Computer Use?',requestedSchema:{type:'object',properties:{}}}};
